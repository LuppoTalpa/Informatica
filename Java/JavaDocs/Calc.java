public class Calc {

    /**
     * Ritorna la somma di due numeri
     *
     * @param a Primo numero da sommare
     * @param b Secondo numero da sommare
     */
    public double getSomma(double a, double b) {
        return a + b;
    }

    /**
     * Ritorna la differenza tra due numeri
     *
     * @param a Primo numero della differenza
     * @param b Secondo numero della differenza
     */
    public double getDifferenza(double a, double b) {
        return a - b;
    }

    /**
     * Ritorna il prodotto tra due numeri
     *
     * @param a Primo numero da moltiplicare
     * @param b Secondo numero da moltiplicare
     */
    public double getProdotto(double a, double b) {
        return a * b;
    }

    /**
     * Ritorna la divisione tra due numeri
     *
     * @param a Primo numero della divisione
     * @param b Secondo numero della divisione
     */
    public double getDivisione(double a, double b) {
        return a / b;
    }
}
